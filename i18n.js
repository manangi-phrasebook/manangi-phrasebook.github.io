// they get answers in. No switch to find or set.

const DEVANAGARI = /[\u0900-\u097F]/; // Devanagari block

/** @param {string} text @returns {'en' | 'ne'} */
export function detectLang(text) {
  return DEVANAGARI.test(text) ? 'ne' : 'en';
}

